//! Spell name → icon file name and aura duration, as Lua tables for AgentCam's observe panel.
//!
//! The 1.12 combat log names spells, never ids, and says neither an aura's icon nor how long it
//! lasts; no 1.12 Lua API maps a spell to either, so the panel's combat-log fallback ships these
//! tables. One icon per name: the icon most of that name's rows use, class spells
//! (`SpellFamilyName` set) counted ahead of the rest, ties broken by the lower spell id. One
//! duration per name: the longest `SpellDuration.dbc` base among its class rows (else among all
//! rows), the top rank's, which is what a levelled agent casts; permanent and over-two-hour
//! durations are left out. Passive spells and rows with no icon are left out of both.
//!
//! ```bash
//! WOW_DATA=<1.12 Data> cargo run -p benilla-formats --example spell_icon_names > addons/AgentCam/AgentCamSpellIcons.lua
//! ```
use std::collections::{BTreeMap, HashMap};

fn main() -> anyhow::Result<()> {
    let data = benilla_formats::wow_data().expect("no WoW install found (set $WOW_DATA)");
    let mut chain = benilla_formats::open_chain(&data)?;
    let catalog = benilla_formats::load_spell_catalog(&mut chain)?;
    let durations = benilla_formats::load_spell_durations(&mut chain)?;
    // name -> (longest class-row duration, longest any-row duration), in ms
    let mut dur_by_name: BTreeMap<String, (i32, i32)> = BTreeMap::new();

    // name -> icon -> (class rows, all rows, lowest id)
    let mut by_name: BTreeMap<String, HashMap<String, (u32, u32, u32)>> = BTreeMap::new();
    for (id, d) in catalog.iter() {
        if d.passive || d.name.is_empty() {
            continue;
        }
        let Some(path) = d.icon.as_deref() else { continue };
        let file = path.rsplit('\\').next().unwrap_or(path);
        if file.is_empty() || d.name.contains(['"', '\\', '\n']) {
            continue;
        }
        let e = by_name
            .entry(d.name.clone())
            .or_default()
            .entry(file.to_string())
            .or_insert((0, 0, u32::MAX));
        if d.spell_family != 0 {
            e.0 += 1;
        }
        if let Some(row) = durations.get(d.duration_index) {
            let ms = row.base_ms;
            if !row.is_permanent() && ms > 0 && ms <= 2 * 3600 * 1000 {
                let dd = dur_by_name.entry(d.name.clone()).or_insert((0, 0));
                if d.spell_family != 0 {
                    dd.0 = dd.0.max(ms);
                }
                dd.1 = dd.1.max(ms);
            }
        }
        e.1 += 1;
        e.2 = e.2.min(id);
    }

    println!("-- Generated by crates/benilla-formats/examples/spell_icon_names.rs from Spell.dbc and");
    println!("-- SpellIcon.dbc: spell name -> icon under Interface\\Icons. Do not edit by hand.");
    println!("AgentCam_SpellIcons = {{");
    for (name, icons) in &by_name {
        let (file, _) = icons
            .iter()
            .max_by(|a, b| {
                (a.1 .0, a.1 .1)
                    .cmp(&(b.1 .0, b.1 .1))
                    .then(b.1 .2.cmp(&a.1 .2))
            })
            .expect("at least one icon per name");
        println!("[\"{name}\"]=\"{file}\",");
    }
    println!("}}");
    println!("-- spell name -> aura duration in ms, for auras the combat log reports without a time");
    println!("AgentCam_SpellDurations = {{");
    for (name, (class_ms, any_ms)) in &dur_by_name {
        let ms = if *class_ms > 0 { *class_ms } else { *any_ms };
        println!("[\"{name}\"]={ms},");
    }
    println!("}}");
    eprintln!("{} names, {} durations", by_name.len(), dur_by_name.len());
    Ok(())
}
